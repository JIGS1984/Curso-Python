#TIPO DE DATOS RANDOM (ALEATORIOS)
import random

#si queremos que el sistema me de un entero aleatorio
print(random.randint(0,100))
#si queremos que el sistma me de un float aleatorio
print(random.random())
#aleatorios entre un valor y otro y con paso
print(random.randrange(0,20,2))
#choice
#aleatorio de unos valores que se le da

print(random.choice(50,20))
